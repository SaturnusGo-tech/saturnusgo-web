import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { after, before, test } from "node:test";
import React from "react";
import { act, create } from "react-test-renderer";
import { TestDataProvider, type TestDataContextValue } from "../../../application/context/TestDataContext";
import { installRenderControls } from "../../support/render-controls";
const require = createRequire(import.meta.url), previous = Object.getOwnPropertyDescriptor(globalThis, "React");
let Menu: typeof import("../../../presentation/workspace-source-menu/AddSourceMenu")["AddSourceMenu"];
before(() => { Object.assign(globalThis, { React }); const restore = installRenderControls(); try { Menu = require("../../../presentation/workspace-source-menu/AddSourceMenu").AddSourceMenu; } finally { restore(); } });
after(() => { if (previous) Object.defineProperty(globalThis, "React", previous); else Reflect.deleteProperty(globalThis, "React"); });
test("source menu offers real providers and keeps connection credentials behind the author permission", async () => {
  const chosen: string[] = [], context = { permissions: { create: true, credentialCreate: false } } as unknown as TestDataContextValue;
  let view: ReturnType<typeof create>;
  await act(async () => { view = create(<TestDataProvider value={context}><Menu ru={false} onChoose={kind => chosen.push(kind)} /></TestDataProvider>); });
  const list = view!.root.findByType("listbox" as never);
  assert.deepEqual(list.props.disabledKeys, ["POSTMAN", "MYSQL", "POSTGRES"]);
  await act(async () => list.props.onAction("POSTMAN"));
  assert.deepEqual(chosen, []);
  await act(async () => list.props.onAction("FILE"));
  assert.deepEqual(chosen, ["FILE"]);
  await act(async () => view!.unmount());
});
